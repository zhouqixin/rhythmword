// AppLayout — 底部导航栏布局
// 用于登录后的所有页面

'use client';

import { usePathname } from 'next/navigation';
import Link from 'next/link';
import { cn } from '@/lib/utils';

const NAV_ITEMS = [
  { href: '/', label: '首页', icon: HomeIcon },
  { href: '/wrongbook', label: '错题本', icon: BookIcon },
  { href: '/shop', label: '商城', icon: ShopIcon },
  { href: '/profile', label: '我的', icon: ProfileIcon },
  { href: '/settings', label: '设置', icon: SettingsIcon },
];

export default function AppLayout({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();

  return (
    <div className="flex flex-col min-h-screen">
      {/* 主内容区 */}
      <main className="flex-1 pb-20">{children}</main>

      {/* 底部导航栏 */}
      <nav className="fixed bottom-0 left-0 right-0 z-50 border-t border-[var(--rhythm-bg-border)] bg-[var(--rhythm-bg-card)]/95 backdrop-blur-md">
        <div className="mx-auto flex max-w-lg items-center justify-around px-2 py-2">
          {NAV_ITEMS.map((item) => {
            const isActive = pathname === item.href;
            return (
              <Link
                key={item.href}
                href={item.href}
                className={cn(
                  'flex flex-col items-center gap-0.5 rounded-lg px-3 py-1.5 transition-colors',
                  isActive
                    ? 'text-[var(--rhythm-primary-light)]'
                    : 'text-[var(--rhythm-neutral-400)] hover:text-[var(--rhythm-neutral-200)]'
                )}
              >
                <item.icon active={isActive} />
                <span className="text-xs font-medium">{item.label}</span>
              </Link>
            );
          })}
        </div>
      </nav>
    </div>
  );
}

